@Composable
fun AllocationTableScreen(
    comparison: OptimizationComparison?,
    searchQuery: String,
    onSearchChange: (String) -> Unit,
    selectedPriority: TaskPriority?,
    onSelectPriority: (TaskPriority?) -> Unit,
    modifier: Modifier = Modifier
) {
    val plan = comparison?.optimizedPlan ?: emptyList()
    val rationales = comparison?.rationales ?: emptyMap()
    var expandedTaskId by remember { mutableStateOf<String?>(null) }
    var filterOnlyBottlenecks by remember { mutableStateOf(false) }

    val filteredSlots = plan.filter { slot ->
        val matchesSearch = searchQuery.isBlank() ||
                slot.task.code.contains(searchQuery, ignoreCase = true) ||
                slot.task.name.contains(searchQuery, ignoreCase = true) ||
                (slot.resource?.code?.contains(searchQuery, ignoreCase = true) == true)

        val matchesPriority = selectedPriority == null || slot.task.priority == selectedPriority
        val matchesBottleneck = !filterOnlyBottlenecks || !slot.isFeasible

        matchesSearch && matchesPriority && matchesBottleneck
    }

    LazyColumn(
        modifier = modifier
            .fillMaxSize()
            .padding(horizontal = 16.dp),
        verticalArrangement = Arrangement.spacedBy(12.dp),
        contentPadding = PaddingValues(top = 12.dp, bottom = 80.dp)
    ) {
        item {
            Column(verticalArrangement = Arrangement.spacedBy(4.dp)) {
                Text(
                    text = "Dynamic Allocation Table",
                    color = TextPrimary,
                    fontSize = 18.sp,
                    fontWeight = FontWeight.Bold
                )
                Text(
                    text = "Detailed mission assignments generated by mathematical optimization. Tap any task to inspect solver decision rationale.",
                    color = TextSecondary,
                    fontSize = 12.sp
                )
            }
        }

        // Search bar
        item {
            OutlinedTextField(
                value = searchQuery,
                onValueChange = onSearchChange,
                modifier = Modifier
                    .fillMaxWidth()
                    .testTag("task_search_field"),
                placeholder = { Text("Search by task code, name, or asset...", fontSize = 12.sp, color = TextMuted) },
                leadingIcon = { Icon(Icons.Default.Search, "Search", tint = CyanAccent, modifier = Modifier.size(18.dp)) },
                trailingIcon = {
                    if (searchQuery.isNotEmpty()) {
                        IconButton(onClick = { onSearchChange("") }) {
                            Icon(Icons.Default.Clear, "Clear", tint = TextMuted, modifier = Modifier.size(16.dp))
                        }
                    }
                },
                singleLine = true,
                colors = OutlinedTextFieldDefaults.colors(
                    focusedBorderColor = CyanAccent,
                    unfocusedBorderColor = NavyCardBorder,
                    focusedContainerColor = NavySurface,
                    unfocusedContainerColor = NavySurface,
                    focusedTextColor = TextPrimary,
                    unfocusedTextColor = TextPrimary
                ),
                shape = RoundedCornerShape(10.dp)
            )
        }

        // Priority filter row
        item {
            Row(
                modifier = Modifier.fillMaxWidth(),
                horizontalArrangement = Arrangement.spacedBy(6.dp),
                verticalAlignment = Alignment.CenterVertically
            ) {
                FilterChip(
                    selected = selectedPriority == null && !filterOnlyBottlenecks,
                    onClick = {
                        onSelectPriority(null)
                        filterOnlyBottlenecks = false
                    },
                    label = { Text("All (${plan.size})", fontSize = 10.sp) },
                    colors = FilterChipDefaults.filterChipColors(
                        selectedContainerColor = ElectricBlue,
                        selectedLabelColor = Color.White
                    ),
                    modifier = Modifier.height(28.dp)
                )

                TaskPriority.entries.take(4).forEach { priority ->
                    val isSelected = selectedPriority == priority && !filterOnlyBottlenecks
                    FilterChip(
                        selected = isSelected,
                        onClick = {
                            filterOnlyBottlenecks = false
                            onSelectPriority(if (isSelected) null else priority)
                        },
                        label = { Text(priority.label, fontSize = 10.sp) },
                        colors = FilterChipDefaults.filterChipColors(
                            selectedContainerColor = when (priority) {
                                TaskPriority.CRITICAL -> StatusDanger
                                TaskPriority.HIGH -> StatusWarning
                                TaskPriority.MEDIUM -> CyanAccent
                                else -> SkyBlue
                            },
                            selectedLabelColor = Color.Black
                        ),
                        modifier = Modifier.height(28.dp)
                    )
                }

                FilterChip(
                    selected = filterOnlyBottlenecks,
                    onClick = {
                        filterOnlyBottlenecks = !filterOnlyBottlenecks
                        if (filterOnlyBottlenecks) onSelectPriority(null)
                    },
                    label = { Text("Bottlenecks", fontSize = 10.sp) },
                    colors = FilterChipDefaults.filterChipColors(
                        selectedContainerColor = StatusDanger,
                        selectedLabelColor = Color.White
                    ),
                    modifier = Modifier.height(28.dp)
                )
            }
        }

        if (filteredSlots.isEmpty()) {
            item {
                Box(
                    modifier = Modifier
                        .fillMaxWidth()
                        .padding(vertical = 32.dp),
                    contentAlignment = Alignment.Center
                ) {
                    Text("No tasks match the active filters.", color = TextMuted, fontSize = 13.sp)
                }
            }
        } else {
            items(filteredSlots, key = { it.task.id }) { slot ->
                val isExpanded = expandedTaskId == slot.task.id
                val rationale = rationales[slot.task.id]

                TaskAllocationCard(
                    slot = slot,
                    rationale = rationale,
                    isExpanded = isExpanded,
                    onToggleExpand = {
                        expandedTaskId = if (isExpanded) null else slot.task.id
                    }
                )
            }
        }
    }
}

@Composable
private fun TaskAllocationCard(
    slot: AllocationSlot,
    rationale: AllocationRationale?,
    isExpanded: Boolean,
    onToggleExpand: () -> Unit
) {
    val task = slot.task
    val priorityColor = when (task.priority) {
        TaskPriority.CRITICAL -> StatusDanger
        TaskPriority.HIGH -> StatusWarning
        TaskPriority.MEDIUM -> CyanAccent
        TaskPriority.LOW -> SkyBlue
        TaskPriority.ROUTINE -> Color(0xFF6EE7B7)
    }

    Card(
        modifier = Modifier
            .fillMaxWidth()
            .clip(RoundedCornerShape(10.dp))
            .clickable { onToggleExpand() }
            .testTag("task_card_${task.code}"),
        colors = CardDefaults.cardColors(containerColor = NavySurface),
        shape = RoundedCornerShape(10.dp),
        border = CardDefaults.outlinedCardBorder().copy(
            brush = androidx.compose.ui.graphics.SolidColor(
                if (!slot.isFeasible) StatusDanger.copy(alpha = 0.6f) else NavyCardBorder
            )
        )
    ) {
        Column(
            modifier = Modifier.padding(14.dp),
            verticalArrangement = Arrangement.spacedBy(8.dp)
        ) {
            // Row 1: Code, Name, Priority Badge
            Row(
                modifier = Modifier.fillMaxWidth(),
                horizontalArrangement = Arrangement.SpaceBetween,
                verticalAlignment = Alignment.CenterVertically
            ) {
                Row(
                    horizontalArrangement = Arrangement.spacedBy(8.dp),
                    verticalAlignment = Alignment.CenterVertically
                ) {
                    Box(
                        modifier = Modifier
                            .clip(RoundedCornerShape(4.dp))
                            .background(priorityColor.copy(alpha = 0.2f))
                            .padding(horizontal = 6.dp, vertical = 2.dp)
                    ) {
                        Text(
                            text = task.code,
                            color = priorityColor,
                            fontSize = 11.sp,
                            fontWeight = FontWeight.ExtraBold
                        )
                    }

                    Text(
                        text = task.name,
                        color = TextPrimary,
                        fontSize = 13.sp,
                        fontWeight = FontWeight.Bold
                    )
                }

                Box(
                    modifier = Modifier
                        .clip(RoundedCornerShape(4.dp))
                        .background(priorityColor.copy(alpha = 0.15f))
                        .padding(horizontal = 6.dp, vertical = 2.dp)
                ) {
                    Text(
                        text = task.priority.label,
                        color = priorityColor,
                        fontSize = 10.sp,
                        fontWeight = FontWeight.Bold
                    )
                }
            }

            // Row 2: Mission Type & Required Role
            Row(
                modifier = Modifier.fillMaxWidth(),
                horizontalArrangement = Arrangement.SpaceBetween,
                verticalAlignment = Alignment.CenterVertically
            ) {
                Text(
                    text = "${task.missionType.displayName} • Req: ${task.missionType.requiredRole.shortTag}",
                    color = TextSecondary,
                    fontSize = 11.sp
                )

                Text(
                    text = "Dur: ${task.durationMinutes}m | Max T+${task.deadlineMinutes}m",
                    color = TextMuted,
                    fontSize = 10.sp
                )
            }

            HorizontalDivider(color = NavyCardBorder.copy(alpha = 0.5f))

            // Row 3: Assigned Asset, Timing, Feasibility
            Row(
                modifier = Modifier.fillMaxWidth(),
                horizontalArrangement = Arrangement.SpaceBetween,
                verticalAlignment = Alignment.CenterVertically
            ) {
                Row(
                    horizontalArrangement = Arrangement.spacedBy(6.dp),
                    verticalAlignment = Alignment.CenterVertically
                ) {
                    Icon(
                        imageVector = if (slot.isFeasible) Icons.Default.FlightTakeoff else Icons.Default.Block,
                        contentDescription = "Status",
                        tint = if (slot.isFeasible) CyanAccent else StatusDanger,
                        modifier = Modifier.size(16.dp)
                    )

                    Text(
                        text = if (slot.isFeasible) "Assigned: ${slot.resource?.code}" else "Unfeasible Bottleneck",
                        color = if (slot.isFeasible) TextPrimary else StatusDanger,
                        fontSize = 12.sp,
                        fontWeight = FontWeight.SemiBold
                    )
                }

                if (slot.isFeasible) {
                    Text(
                        text = "T+${slot.scheduledStart}m → T+${slot.scheduledEnd}m (${if (slot.delayMinutes > 0) "+${slot.delayMinutes}m delay" else "On-time"})",
                        color = if (slot.delayMinutes > 0) StatusWarning else StatusSuccess,
                        fontSize = 11.sp,
                        fontWeight = FontWeight.Bold
                    )
                }
            }

            // Expandable Decision Explainability Rationale Drawer
            AnimatedVisibility(visible = isExpanded) {
                Column(
                    modifier = Modifier
                        .fillMaxWidth()
                        .padding(top = 8.dp)
                        .clip(RoundedCornerShape(8.dp))
                        .background(NavySurfaceVariant)
                        .padding(12.dp),
                    verticalArrangement = Arrangement.spacedBy(8.dp)
                ) {
                    Row(
                        verticalAlignment = Alignment.CenterVertically,
                        horizontalArrangement = Arrangement.spacedBy(6.dp)
                    ) {
                        Icon(Icons.Default.Psychology, "AI Rationale", tint = CyanAccent, modifier = Modifier.size(16.dp))
                        Text(
                            text = "SOLVER DECISION RATIONALE",
                            color = CyanAccent,
                            fontSize = 11.sp,
                            fontWeight = FontWeight.Bold,
                            letterSpacing = 0.5.sp
                        )
                    }

                    Text(
                        text = rationale?.primaryReason ?: slot.rationale,
                        color = TextPrimary,
                        fontSize = 11.sp,
                        lineHeight = 15.sp
                    )

                    if (!rationale?.constraintChecks.isNullOrEmpty()) {
                        Text(
                            text = "Constraint Satisfactions:",
                            color = TextSecondary,
                            fontSize = 10.sp,
                            fontWeight = FontWeight.Bold
                        )

                        rationale!!.constraintChecks.forEach { check ->
                            Row(
                                modifier = Modifier.fillMaxWidth(),
                                horizontalArrangement = Arrangement.SpaceBetween,
                                verticalAlignment = Alignment.CenterVertically
                            ) {
                                Row(
                                    horizontalArrangement = Arrangement.spacedBy(4.dp),
                                    verticalAlignment = Alignment.CenterVertically
                                ) {
                                    Icon(
                                        imageVector = if (check.satisfied) Icons.Default.Check else Icons.Default.Close,
                                        contentDescription = "Satisfied",
                                        tint = if (check.satisfied) StatusSuccess else StatusDanger,
                                        modifier = Modifier.size(12.dp)
                                    )
                                    Text(check.constraintName, color = TextPrimary, fontSize = 10.sp)
                                }
                                Text(check.detail, color = TextMuted, fontSize = 9.sp)
                            }
                        }
                    }

                    if (!rationale?.alternativesConsidered.isNullOrEmpty()) {
                        Text(
                            text = "Alternative Fleet Evaluated:",
                            color = TextSecondary,
                            fontSize = 10.sp,
                            fontWeight = FontWeight.Bold
                        )

                        rationale!!.alternativesConsidered.forEach { alt ->
                            Row(
                                modifier = Modifier.fillMaxWidth(),
                                horizontalArrangement = Arrangement.SpaceBetween,
                                verticalAlignment = Alignment.CenterVertically
                            ) {
                                Text(alt.resourceCode, color = if (alt.accepted) CyanAccent else TextMuted, fontSize = 10.sp, fontWeight = FontWeight.Bold)
                                Text(
                                    text = if (alt.accepted) "Accepted (Optimal)" else (alt.rejectionReason?.take(40) ?: "Rejected"),
                                    color = if (alt.accepted) StatusSuccess else TextMuted,
                                    fontSize = 9.sp
                                )
                            }
                        }
                    }
                }
            }

            // Click hint
            Row(
                modifier = Modifier.fillMaxWidth(),
                horizontalArrangement = Arrangement.End,
                verticalAlignment = Alignment.CenterVertically
            ) {
                Text(
                    text = if (isExpanded) "Hide explanation ▲" else "Explain allocation ▼",
                    color = CyanAccent,
                    fontSize = 10.sp,
                    fontWeight = FontWeight.SemiBold
                )
            }
        }
    }
}
